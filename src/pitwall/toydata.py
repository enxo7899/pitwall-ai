"""Toy arithmetic examples for pipeline smoke tests only.

Generated by code (no language model wrote them), deliberately trivial, and never
used for the real adapter. Every answer opens with the same phrase, so it is easy to
see whether a few training steps changed the model's behaviour.
"""

from __future__ import annotations

import random

OPENING = "Lights out and away we go:"
HELD_OUT_QUESTION = "What is 17 plus 25?"  # never in the toy training set (checked by a test)

_OPERATIONS = (
    ("plus", lambda a, b: a + b),
    ("minus", lambda a, b: a - b),
    ("times", lambda a, b: a * b),
)


def make_toy_examples(n: int, seed: int = 0) -> list[dict[str, str]]:
    """n question/answer pairs like 'What is 12 times 4?' -> 'Lights out and away we go: 12 times 4 is 48. Chequered flag!'."""
    rng = random.Random(seed)
    examples = []
    while len(examples) < n:
        a, b = rng.randint(2, 50), rng.randint(2, 50)
        name, op = rng.choice(_OPERATIONS)
        question = f"What is {a} {name} {b}?"
        if question == HELD_OUT_QUESTION:
            continue
        examples.append({"question": question, "answer": f"{OPENING} {a} {name} {b} is {op(a, b)}. Chequered flag!"})
    return examples
