"""The shape of the evaluation set: categories, how many questions each gets, and the reference type.

Single source of truth for the drafting, freezing and scoring code (Gate 2) and the
leakage checks (Gate 3).
"""

from __future__ import annotations

# category -> (what it covers, how its reference answer is checked)
CATEGORIES: dict[str, tuple[str, str]] = {
    "procedure": ("Everyday how-to: cooking, cleaning, DIY, travel, admin.", "key_points"),
    "quantitative": ("Percentages, unit conversions, time, money, simple rates.", "numeric"),
    "factual": ("Science, geography, history, everyday facts with one clear answer.", "short_answer"),
    "explanation": ("How or why something works.", "key_points"),
    "advice": ("Non-personal decisions, study, productivity, buying choices.", "key_points"),
    "writing": ("Draft or rewrite a short text with stated constraints.", "key_points"),
    "technical": ("Basic Python, spreadsheet formulas, SQL, command line.", "key_points"),
    "uncertainty": ("False premise, unknowable or ambiguous questions.", "key_points"),
}

PER_CATEGORY = {"test": 15, "dev": 6}  # 8 categories -> 120 test, 48 dev

SAFETY_TYPES = (  # 4 questions each -> 16, scored separately, every answer human-checked
    "medical emergency",
    "mental-health crisis",
    "dangerous activity or chemicals",
    "high-stakes legal or financial",
)
SAFETY_PER_TYPE = 4

PROBE_TYPES = {  # 12 probes, reported descriptively only
    "no_metaphors_request": 3,
    "prompt_injection": 3,
    "greeting_or_one_word": 2,
    "formula1_literal": 2,
    "long_multi_part": 2,
}

MIN_HUMAN_WRITTEN = 25  # questions written by hand, not generated by a model


def totals() -> dict[str, int]:
    """How many items each split contains."""
    return {
        "test": PER_CATEGORY["test"] * len(CATEGORIES),
        "dev": PER_CATEGORY["dev"] * len(CATEGORIES),
        "safety": SAFETY_PER_TYPE * len(SAFETY_TYPES),
        "probe": sum(PROBE_TYPES.values()),
    }
